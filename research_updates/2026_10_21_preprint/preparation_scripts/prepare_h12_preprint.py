def inline(s):
    # Math is already LaTeX; protect it while escaping ordinary prose.
    pieces = re.split(r'(\$[^$]*\$|`[^`]*`|\[[^\]]+\]\([^)]*\))',s)
    result=[]
    for p in pieces:
        if p.startswith('$') and p.endswith('$'): result.append(p)
        elif p.startswith('`') and p.endswith('`'): result.append('\\path{'+p[1:-1]+'}')
        elif re.fullmatch(r'\[[^\]]+\]\([^)]*\)',p):
            label,url=re.match(r'\[([^\]]+)\]\(([^)]*)\)',p).groups()
            if not url.startswith('http'): result.append(inline(label))
            else: result.append('\\href{'+url+'}{'+inline(label)+'}')
        else:
            p=p.replace('&',r'\&').replace('%',r'\%').replace('_',r'\_').replace('#',r'\#')
            p=re.sub(r'https://[^\s)]+',lambda m:r'\url{'+m.group(0).rstrip('.')+'}'+('.' if m.group(0).endswith('.') else ''),p)
            p=re.sub(r'\*\*(.*?)\*\*',r'\\textbf{\1}',p)
            p=p.replace('∎',r'\hfill$\square$')
            result.append(p)
    return ''.join(result)

