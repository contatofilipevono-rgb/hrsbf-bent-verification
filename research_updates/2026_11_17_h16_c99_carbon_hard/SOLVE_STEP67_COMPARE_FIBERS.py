"""Zero-trust comparison of two reduced B0_11 systems from Step 60.

Tests exact equality of Boolean polynomial row spans over GF(2), not merely
similar ranks. If row spans match, the polynomial zero sets are identical and
the Step 65 certificate can transfer to fiber 0 without re-enumeration.

NOTE: equality up to a variable transformation is NOT tested here.
"""
import hashlib
import json
from pathlib import Path


def canonical_basis(rows):
    basis = {}
    for vector in rows:
        while vector:
            p = vector.bit_length() - 1
            if p not in basis:
                basis[p] = vector
                break
            vector ^= basis[p]
    # canonical RREF (not just echelon basis)
    for p in sorted(basis):
        for q in sorted(basis):
            if q != p and (basis[q] >> p) & 1:
                basis[q] ^= basis[p]
    return tuple(basis[p] for p in sorted(basis, reverse=True))


def main():
    files = [
        Path("fiber0/step60_fiber.json"),
        Path("fiber64/step60_fiber.json"),
    ]
    raw = [path.read_bytes() for path in files]
    data = [json.loads(x) for x in raw]
    assert all(x["original_count"] == 63 and x["variables"] == 59 for x in data)
    polys = [x["polynomials"][:63] for x in data]
    assert all(len(x) == 63 for x in polys)
    universe = sorted(set(m for rows in polys for row in rows for m in row))
    assert all(0 <= m < (1 << 59) for m in universe)
    assert len(universe) > 0
    monomial_to_index = {m:i for i,m in enumerate(universe)}
    packed = [
        [sum(1 << monomial_to_index[m] for m in row) for row in rows]
        for rows in polys
    ]
    basis = [canonical_basis(x) for x in packed]
    combined = canonical_basis(packed[0] + packed[1])
    union_rank = len(combined)
    row_equal = basis[0] == basis[1]
    # If identical row spaces, every polynomial of one system is a GF2
    # combination of those in the other, so solution sets coincide.
    summary = {
        "scope": "B0_11 Step60 fibers 0 and 64, ORIGINAL 63 equations",
        "fiber_source_sha256": [hashlib.sha256(x).hexdigest() for x in raw],
        "variables": 59, "monomials_union": len(universe),
        "rank_fiber0": len(basis[0]), "rank_fiber64": len(basis[1]),
        "rank_union": union_rank, "row_spaces_equal": row_equal,
        "transfers_step65_unsat_64_to_0_by_row_span": row_equal,
        "warning": "No claim about other fibers or full B0_11; no change of variables tested.",
    }
    if row_equal:
        assert len(basis[0]) == union_rank
        summary["proof"] = "Polynomial ideals generated by both systems coincide via GF(2) linear combinations."
    else:
        assert union_rank >= max(len(basis[0]), len(basis[1]))
    Path("step67_fiber_compare.json").write_text(json.dumps(summary,indent=2)+"\n")
    print("STEP67_ROWSPAN",json.dumps(summary),flush=True)


if __name__ == "__main__":
    main()
