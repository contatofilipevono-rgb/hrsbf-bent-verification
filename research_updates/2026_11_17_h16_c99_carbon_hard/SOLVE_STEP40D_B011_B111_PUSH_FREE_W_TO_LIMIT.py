def run_cell(cell_name, lib_diag, lib9, lib_cg, lib_sh, orbits, layer_vecs,
             v6_list, rot4_data, fiber_meta, layers, c0x0, mon_to_orb_arr, reps12, reps11, tbl):
    t0 = time.perf_counter()
    print(f"\n==================== [{cell_name}] STEP 40D: PUSHING FREE_W TO THE LIMIT (rk<=24) ====================", flush=True)
    c99, c57, c113 = int(cell_name[1]), int(cell_name[3]), int(cell_name[4])
    free111, origin111, cb111 = b09.build_pure_111_basis(c99, c57, c113)
    n, n_cw = tbl["n"], tbl["n_col_words"]
    n_cols = tbl["off0"] + 1
    mask64 = (1 << 64) - 1

    orb_map = (ctypes.c_int * 116)(*([-1] * 116))
    for i, j in enumerate(free111): orb_map[j] = i
    orb_map[0] = -3; orb_map[115] = -1
    orb_map[99] = -2 if c99 else -1
    orb_map[57] = -2 if c57 else -1
    orb_map[113] = -2 if c113 else -1
    L_set = set(diag_v2.L_INDICES)
    L_vars_py = [i for i, j in enumerate(free111) if j in L_set]
    L_vars_arr = (ctypes.c_int * len(L_vars_py))(*L_vars_py)

    n_cg = len(reps12) + len(reps11)
    cg_buf = (ctypes.c_uint64 * (n_cg * n_cw))()
    for idx, I_m in enumerate(reps12):
        rptr = ctypes.cast(ctypes.byref(cg_buf, idx * n_cw * 8), ctypes.POINTER(ctypes.c_uint64))
        lib_cg.build_cg12_row_c(
            I_m, mon_to_orb_arr, orb_map, c99, L_vars_arr, len(L_vars_py),
            n, tbl["off2"], tbl["off1"], tbl["off0"], n_cw, tbl["col2_base"], tbl["col3_base"], rptr
        )
    for idx, I_m in enumerate(reps11):
        rptr = ctypes.cast(ctypes.byref(cg_buf, (len(reps12) + idx) * n_cw * 8), ctypes.POINTER(ctypes.c_uint64))
        lib_cg.build_cg11_row_c(
            I_m, mon_to_orb_arr, orb_map, c99, L_vars_arr, len(L_vars_py),
            n, tbl["off2"], tbl["off1"], tbl["off0"], n_cw, tbl["col2_base"], tbl["col3_base"], rptr
        )

    sys_data = diag_v2.build_cell_algebraic_system(cell_name, lib_diag, orbits, v6_list, rot4_data, fiber_meta, extract_sec=18.0)
    cyc_cubs = s9.extract_verified_cyclotomic_cubics(cell_name, orbits, origin111, cb111, layers, c0x0)
    n_base = sum(sys_data["deg_pivs_111"].values())
    total_raw = n_base + len(cyc_cubs) + n_cg
    raw_buf = (ctypes.c_uint64 * (total_raw * n_cw))()
    ctypes.memmove(raw_buf, sys_data["rows_c"], n_base * n_cw * 8)
    for idx_c, (_, poly) in enumerate(cyc_cubs):
        s9.pset_to_row(poly, raw_buf, n_base + idx_c, tbl)
    ctypes.memmove(ctypes.byref(raw_buf, (n_base + len(cyc_cubs)) * n_cw * 8), cg_buf, n_cg * n_cw * 8)

    root = s9.run_branch_cascade(lib9, raw_buf, [], list(range(total_raw)), {}, [], tbl, max_xl_rounds=10, verify_subst=True)
    forms_L1 = s16.extract_forms_from_orb_vecs(cb111, layer_vecs["L1"][1], layer_vecs["L1"][0])
    eta_free = s16.reduce_forms_mod_pivs(forms_L1, root["_lin_pivs"])
    ex_eta = [(eta_free[k], 0) for k in range(len(eta_free))]
    sr = s9.run_branch_cascade(
        lib9, root["_buf"], root["_quad_ids"], root["_cub_ids"], root["_lin_pivs"],
        ex_eta, tbl, max_xl_rounds=20, verify_subst=True
    )
    qps = [s9.row_to_pset(sr["_buf"], qr, tbl) for qr in sr["_quad_ids"]]
    ana = s16.analyze_quad_system(qps)
    W_rref = s19.strict_rref_masks(list(ana["W_piv"].values()))
    W_pivs = sorted(W_rref.keys())
    W_set = set(W_pivs)
    W_forms = [W_rref[p] for p in W_pivs]
    active_now = sorted(i for i in range(n) if i not in sr["_lin_pivs"])
    R_vars = [v for v in active_now if v not in W_set]
    R_set = set(R_vars)

    eq_ids = list(sr["_quad_ids"]) + list(sr["_cub_ids"])
    M_eq = len(eq_ids)
    work = (ctypes.c_uint64 * (M_eq * n_cw))()
    for i, rid in enumerate(eq_ids):
        ctypes.memmove(ctypes.byref(work, i * n_cw * 8), ctypes.byref(sr["_buf"], rid * n_cw * 8), n_cw * 8)
    for p in W_pivs:
        rest = W_rref[p] ^ (1 << p)
        if rest:
            lib_sh.shear_subst_var_batch(
                work, M_eq, n_cw, n, tbl["off2"], tbl["off1"], tbl["off0"],
                tbl["col2_base"], tbl["col3_base"], tbl["col_deg"], tbl["col_v0"], tbl["col_v1"], tbl["col_v2"],
                p, rest & mask64, rest >> 64
            )
    n_q = len(sr["_quad_ids"])
    tail_forms = []
    for qi in range(n_q):
        qps_sh = s9.row_to_pset(work, qi, tbl)
        rmask = 0
        for m in qps_sh:
            if m.bit_count() == 1:
                v = m.bit_length() - 1
                if v in R_set: rmask |= (1 << v)
        if rmask: tail_forms.append(rmask)
    T_rref = s19.strict_rref_masks(tail_forms)
    T_pivs = sorted(T_rref.keys())
    T_set = set(T_pivs)
    RF_vars = [v for v in R_vars if v not in T_set]
    RF_set = set(RF_vars)
    nW, nT, nRF = len(W_pivs), len(T_pivs), len(RF_vars)
    for p in T_pivs:
        rest = T_rref[p] ^ (1 << p)
        if rest:
            lib_sh.shear_subst_var_batch(
                work, M_eq, n_cw, n, tbl["off2"], tbl["off1"], tbl["off0"],
                tbl["col2_base"], tbl["col3_base"], tbl["col_deg"], tbl["col_v0"], tbl["col_v1"], tbl["col_v2"],
                p, rest & mask64, rest >> 64
            )

    col_keys, col_meta = [], []
    for c in range(n_cols):
        d = int(tbl["col_deg"][c])
        vs = []
        if d >= 1: vs.append(int(tbl["col_v0"][c]))
        if d >= 2: vs.append(int(tbl["col_v1"][c]))
        if d >= 3: vs.append(int(tbl["col_v2"][c]))
        drf = sum(1 for v in vs if v in RF_set)
        dt_c = sum(1 for v in vs if v in T_set)
        col_meta.append((drf, dt_c, d))
        col_keys.append((3 - drf, 3 - dt_c, 3 - d, c))
    col_keys.sort()
    orig_to_perm = (ctypes.c_int * n_cols)()
    perm_to_orig = [0] * n_cols
    for pc, (_, _, _, oc) in enumerate(col_keys): orig_to_perm[oc] = pc; perm_to_orig[pc] = oc
    perm_buf = (ctypes.c_uint64 * (M_eq * n_cw))()
    lib_sh.remap_rows_by_perm(work, perm_buf, M_eq, n_cw, n_cols, orig_to_perm)
    piv_idx = (ctypes.c_int * n_cols)(*([-1] * n_cols))
    ech_rows = []
    for r in range(M_eq):
        pc = lib9.gf2_echelon_insert_s9(perm_buf, r, n_cw, piv_idx, n_cols)
        if pc >= 0:
            ech_rows.append((r, col_meta[perm_to_orig[pc]]))
    inv_perm = (ctypes.c_int * n_cols)(*perm_to_orig)
    std_ech = (ctypes.c_uint64 * (M_eq * n_cw))()
    lib_sh.remap_rows_by_perm(perm_buf, std_ech, M_eq, n_cw, n_cols, inv_perm)

    w_idx = {v: i for i, v in enumerate(W_pivs)}
    rf_idx = {v: i for i, v in enumerate(RF_vars)}

    M1_psets = [s9.row_to_pset(std_ech, r_id, tbl) for r_id, (drf, dt_c, _) in ech_rows if drf == 1 and dt_c == 0]
    nM = len(M1_psets)
    M0 = np.zeros((nM, nRF), dtype=np.uint8)
    Mk = np.zeros((nW, nM, nRF), dtype=np.uint8)
    for ri, ps in enumerate(M1_psets):
        for m in ps:
            vs = [b for b in range(n) if (m >> b) & 1]
            rfvs = [rf_idx[v] for v in vs if v in RF_set]
            if len(rfvs) != 1: continue
            rfi = rfvs[0]
            wvs = [w_idx[v] for v in vs if v in w_idx]
            if len(wvs) == 0: M0[ri, rfi] ^= 1
            elif len(wvs) == 1: Mk[wvs[0], ri, rfi] ^= 1

    K_R = s40a.gf2_nullspace_np(Mk.reshape(nW * nM, nRF))
    M0_KR = (M0 @ K_R.T) & 1
    L_core = s40a.gf2_nullspace_np(M0_KR.T)
    n_core_rows = L_core.shape[0]
    _, kr_pivs = s40a.gf2_rref_np(K_R)
    core_rf_cols = [c for c in range(nRF) if c not in set(kr_pivs)]
    nRC = len(core_rf_cols)
    Mk_c = np.zeros((nW, n_core_rows, nRC), dtype=np.uint8)
    for k in range(nW):
        Mk_c[k] = (L_core @ Mk[k])[:, core_rf_cols] & 1

    def mat_of(cm):
        acc = np.zeros((n_core_rows, nRC), dtype=np.uint8)
        for k in range(nW):
            if (cm >> k) & 1: acc ^= Mk_c[k]
        return acc

    # Expanded MinRank up to rk <= 24!
    found_low = {}
    def record_c(cm):
        if cm == 0 or cm in found_low: return False
        rk = len(s40a.gf2_rref_np(mat_of(cm))[1])
        if rk <= 24:
            found_low[cm] = rk
            return True
        return False

    for i in range(nW):
        record_c(1 << i)
        for j in range(i + 1, nW):
            record_c((1 << i) | (1 << j))

    tested_v = set()
    rng = random.Random(404044)
    def probe_v(v):
        key = v.tobytes()
        if key in tested_v: return
        tested_v.add(key)
        Bv = np.zeros((n_core_rows, nW), dtype=np.uint8)
        for k in range(nW):
            Bv[:, k] = (Mk_c[k] @ v) & 1
        ker_c = s40a.gf2_nullspace_np(Bv)
        for row in ker_c:
            cm = sum((1 << k) for k in range(nW) if row[k])
            record_c(cm)

    for j in range(nRC):
        e = np.zeros(nRC, dtype=np.uint8); e[j] = 1
        probe_v(e)
    for rnd in range(4):
        cands = [cm for cm, rk in sorted(found_low.items(), key=lambda x: x[1]) if 1 <= rk <= 22][:18]
        for cm in cands:
            K = s40a.gf2_nullspace_np(mat_of(cm))
            for row in K:
                probe_v(row)
            if K.shape[0] >= 2:
                for _ in range(30):
                    a, b = rng.randrange(K.shape[0]), rng.randrange(K.shape[0])
                    if a != b: probe_v(K[a] ^ K[b])
        bas_cur, _ = s40c.gf2_basis_masks([cm for cm, _ in sorted(found_low.items(), key=lambda x: x[1])])
        for i in range(min(len(bas_cur), 25)):
            for j in range(i + 1, min(len(bas_cur), 25)):
                record_c(bas_cur[i] ^ bas_cur[j])
        print(f"    [MinRank round {rnd+1}] total low(<=24)={len(found_low)}, basis_dim={len(bas_cur)}", flush=True)

    # Extend the low-rank basis to a FULL basis of F_2^{nW} using remaining standard unit vectors sorted by rank!
    sorted_low = sorted(found_low.items(), key=lambda x: (x[1], x[0].bit_count()))
    full_cands = [cm for cm, _ in sorted_low] + [1 << k for k in range(nW)]
    full_basis, _ = s40c.gf2_basis_masks(full_cands)
    assert len(full_basis) == nW
    bas_rks = [found_low.get(cm, len(s40a.gf2_rref_np(mat_of(cm))[1])) for cm in full_basis]
    print(f"  [{cell_name}] Full ordered basis (nW={nW}) ranks: {bas_rks}", flush=True)

    # Print touched_rows growth along the flag L_4, L_8, ..., L_36!
    for d_free in [4, 8, 12, 16, 20, 22, 24, 26, 28, 30, 32, 34, 36]:
        if d_free > nW: continue
        mats = np.array([mat_of(cm) for cm in full_basis[:d_free]], dtype=np.uint8)
        col_stack = np.transpose(mats, (0, 2, 1)).reshape(d_free * nRC, n_core_rows)
        _, rp = s40a.gf2_rref_np(col_stack)
        row_stack = mats.reshape(d_free * n_core_rows, nRC)
        kr = s40a.gf2_nullspace_np(row_stack)
        print(f"    Flag L_{d_free:2d}: max_rk={max(bas_rks[:d_free]):2d} | untouched_rows={n_core_rows-len(rp):2d}/{n_core_rows} | common_ker={kr.shape[0]:2d}/{nRC}", flush=True)

    # LIVE SHATTER TEST PUSHING d_free TO THE LIMIT!
    print(f"\n  --- PUSHING d_free TO THE LIMIT ({cell_name}) ---", flush=True)
    rng_sh = random.Random(404045)
    if cell_name == "B0_11":
        test_dls = [22, 24, 26, 28, 30, 32, 34, 36]
    else:
        test_dls = [8, 10, 12, 14, 16, 18, 20, 24]

    for d_free in test_dls:
        if d_free >= nW: continue
        sub_L = np.zeros((d_free, nW), dtype=np.uint8)
        for ri, cm in enumerate(full_basis[:d_free]):
            for k in range(nW):
                if (cm >> k) & 1: sub_L[ri, k] = 1
        F_sub = s40a.gf2_nullspace_np(sub_L)
        k_fix = F_sub.shape[0]
        fix_forms = []
        for row in F_sub:
            fm = 0
            for k in range(nW):
                if row[k]: fm ^= W_forms[k]
            fix_forms.append(fm)
        n_cl = 0
        min_N, max_q = 999, 0
        t_tr = time.perf_counter()
        for tr in range(4):
            rb = rng_sh.getrandbits(k_fix)
            ex_w = [(fix_forms[j], (rb >> j) & 1) for j in range(k_fix)]
            sub = s9.run_branch_cascade(
                lib9, sr["_buf"], sr["_quad_ids"], sr["_cub_ids"], sr["_lin_pivs"],
                ex_w, tbl, max_xl_rounds=20, verify_subst=(tr == 0)
            )
            if sub["closed_unsat"]: n_cl += 1
            else:
                min_N = min(min_N, 111 - len(sub["_lin_pivs"]))
                max_q = max(max_q, len(sub["_quad_ids"]))
        print(f"    [FREE L_{d_free:2d} (k_fix={k_fix:2d})]: CLOSED={n_cl}/4 ({time.perf_counter()-t_tr:.1f}s) | open_min_N={min_N}, open_max_q={max_q}", flush=True)
        if n_cl == 0:
            break

    print(f"[{cell_name}] STEP 40D DONE ({time.perf_counter()-t0:.1f}s)", flush=True)


